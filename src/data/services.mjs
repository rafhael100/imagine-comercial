export function toAbsoluteUrl(path, site = 'https://imaginecomunicacao.com.br') {
  if (!/^\/[a-z0-9\-/]*$/.test(path) || !path.endsWith('/')) {
    throw new Error('Invalid public canonical path: ' + path);
  }
  return new URL(path, site).toString();
}
